-- 1. Количество изданий, выписанных каждым из подписчиков в текущем году
SELECT 
    p.[ФИО_или_наименование] AS Подписчик,
    COUNT(s.[Индекс_издания]) AS Количество_изданий
FROM dbo.Подписка s
JOIN dbo.Подписчики p ON s.[Код_подписчика] = p.[Код_подписчика]
WHERE YEAR(s.[Дата_начала_подписки]) = YEAR(GETDATE())
GROUP BY p.[ФИО_или_наименование];

-- 2. Список изданий-журналов «I-ой» страны на «J-ом» языке
SELECT 
    i.[Наименование_издания],
    i.[Цена_за_месяц],
    c.[Наименование] AS Страна,
    y.[Наименование] AS Язык
FROM dbo.Издание i
JOIN dbo.Страны c ON i.[Код_страны_издания] = c.[Код_страны]
JOIN dbo.Язык_издания y ON i.[Код_языка_издания] = y.[Код_языка_издания]
JOIN dbo.Тип_издания t ON i.[Код_типа_издания] = t.[Код_типа_издания]
WHERE t.[Наименование] = 'Журнал'
  AND c.[Наименование] = 'Франция'
  AND y.[Наименование] = 'Французский';

-- 3. Подписка, оформленная «I-ым» сотрудником в текущем месяце
SELECT 
    s.[Код_подписчика],
    e.[ФИО] AS Сотрудник,
    p.[ФИО_или_наименование] AS Подписчик,
    i.[Наименование_издания] AS Издание,
    s.[Дата_начала_подписки]
FROM dbo.Подписка s
JOIN dbo.Сотрудники e ON s.[Код_сотрудника] = e.[Код_сотрудника]
JOIN dbo.Подписчики p ON s.[Код_подписчика] = p.[Код_подписчика]
JOIN dbo.Издание i ON s.[Индекс_издания] = i.[Индекс_издания]
WHERE e.[ФИО] = N'Иванов Иван Иванович'
  AND MONTH(s.[Дата_начала_подписки]) = MONTH(GETDATE())
  AND YEAR(s.[Дата_начала_подписки]) = YEAR(GETDATE());

-- 4. Список изданий-газет ценою в диапазоне от … до …
SELECT 
    i.[Наименование_издания],
    t.[Наименование] AS Тип_издания,
    i.[Цена_за_месяц]
FROM dbo.Издание i
JOIN dbo.Тип_издания t ON i.[Код_типа_издания] = t.[Код_типа_издания]
WHERE t.[Наименование] = 'Газета'
  AND i.[Цена_за_месяц] BETWEEN 500 AND 1500;

-- 5. Список подписчиков, проживающих по адресу ул. «…»
SELECT 
    [ФИО_или_наименование],
    [Адрес],
    [Телефон]
FROM dbo.Подписчики
WHERE [Адрес] LIKE N'%ул. Ленина%';
