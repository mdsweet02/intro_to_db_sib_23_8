SELECT 
    z.[Номер заказа],
    z.[ФИО заказчика],
    z.[Дата оформления],
    z.[Сумма заказа],
    u.[Наименование] AS "Услуга",
    r.[ФИО] AS "Работник"
FROM Заказ_услуги AS zu
JOIN Заказы AS z ON zu.[Номер заказа] = z.[Номер заказа]
JOIN Работники AS r ON zu.[Код работника] = r.[Табельный номер]
JOIN Услуги AS u ON zu.[Код услуги] = u.[Код услуги]
WHERE zu.[Код работника] = 3
  AND z.[Дата выполнения] = CAST(GETDATE() AS DATE);
